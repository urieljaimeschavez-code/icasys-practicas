-- Ejecutar en SQL Editor del proyecto Supabase. No contiene contraseñas.
-- Las tablas no pertenecen a public y no se exponen a la Data API.
BEGIN;
CREATE SCHEMA IF NOT EXISTS icasys;
REVOKE ALL ON SCHEMA icasys FROM PUBLIC, anon, authenticated;
SET LOCAL search_path TO icasys, pg_catalog;

CREATE TABLE IF NOT EXISTS users (
 id TEXT PRIMARY KEY, name TEXT NOT NULL,
 email TEXT NOT NULL UNIQUE CHECK(email=lower(email)),
 role TEXT NOT NULL CHECK(role IN ('student','advisor','admin')),
 password_hash TEXT NOT NULL,
 active INTEGER NOT NULL DEFAULT 1 CHECK(active IN(0,1)),
 must_change INTEGER NOT NULL DEFAULT 1 CHECK(must_change IN(0,1)),
 created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS.US')
);
CREATE TABLE IF NOT EXISTS placements (
 id TEXT PRIMARY KEY, student_id TEXT NOT NULL REFERENCES users(id),advisor_id TEXT NOT NULL REFERENCES users(id),
 school TEXT NOT NULL,project TEXT NOT NULL,start TEXT NOT NULL,"end" TEXT NOT NULL,
 target DOUBLE PRECISION NOT NULL CHECK(target>=1 AND target<=2000),version INTEGER NOT NULL DEFAULT 1,
 created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS.US'),
 CHECK(start<="end")
);
CREATE INDEX IF NOT EXISTS placement_student ON placements(student_id);
CREATE INDEX IF NOT EXISTS placement_advisor ON placements(advisor_id);
CREATE TABLE IF NOT EXISTS activities (
 id TEXT PRIMARY KEY,placement_id TEXT NOT NULL REFERENCES placements(id),title TEXT NOT NULL,description TEXT NOT NULL,
 date TEXT NOT NULL,hours DOUBLE PRECISION NOT NULL CHECK(hours>=0.5 AND hours<=12 AND hours*2=floor(hours*2)),
 status TEXT NOT NULL CHECK(status IN('draft','pending','correction','approved')),
 version INTEGER NOT NULL DEFAULT 1,
 created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS.US'),
 updated_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS.US')
);
CREATE INDEX IF NOT EXISTS activity_placement ON activities(placement_id);
CREATE TABLE IF NOT EXISTS evidence (
 activity_id TEXT PRIMARY KEY REFERENCES activities(id),name TEXT NOT NULL,mime TEXT NOT NULL,
 storage_key TEXT NOT NULL UNIQUE,size INTEGER NOT NULL CHECK(size>0 AND size<=2097152),sha256 TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS reviews (
 id TEXT PRIMARY KEY,activity_id TEXT NOT NULL REFERENCES activities(id),reviewer_id TEXT NOT NULL REFERENCES users(id),
 decision TEXT NOT NULL CHECK(decision IN('approved','correction')),comment TEXT NOT NULL,
 created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS.US')
);
CREATE INDEX IF NOT EXISTS review_activity ON reviews(activity_id);
CREATE TABLE IF NOT EXISTS sessions (
 token_hash TEXT PRIMARY KEY,user_id TEXT NOT NULL REFERENCES users(id),csrf TEXT NOT NULL,expires_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_user_idx ON sessions(user_id);
CREATE TABLE IF NOT EXISTS login_attempts (key TEXT PRIMARY KEY,failures INTEGER NOT NULL,reset_at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS audit_log (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id TEXT REFERENCES users(id),action TEXT NOT NULL,entity_id TEXT,
 created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS.US')
);
-- Journal of objects uploaded before a transaction commits. Entries remain when
-- a DB failure occurs, so the private object can be reconciled without data loss.
CREATE TABLE IF NOT EXISTS storage_uploads (
 storage_key TEXT PRIMARY KEY,created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS.US')
);
REVOKE ALL ON ALL TABLES IN SCHEMA icasys FROM PUBLIC,anon,authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA icasys FROM PUBLIC,anon,authenticated;
ALTER DEFAULT PRIVILEGES IN SCHEMA icasys REVOKE ALL ON TABLES FROM PUBLIC,anon,authenticated;
-- No policies allow browser roles to read these tables. The Node server uses
-- its private database connection; Supabase Auth is not used in this version.
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE placements ENABLE ROW LEVEL SECURITY;
ALTER TABLE activities ENABLE ROW LEVEL SECURITY;
ALTER TABLE evidence ENABLE ROW LEVEL SECURITY;
ALTER TABLE reviews ENABLE ROW LEVEL SECURITY;
ALTER TABLE sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE login_attempts ENABLE ROW LEVEL SECURITY;
ALTER TABLE audit_log ENABLE ROW LEVEL SECURITY;
ALTER TABLE storage_uploads ENABLE ROW LEVEL SECURITY;
COMMIT;
